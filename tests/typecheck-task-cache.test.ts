import {execFileSync, spawnSync} from "node:child_process";
import {
	appendFileSync,
	cpSync,
	existsSync,
	mkdirSync,
	mkdtempSync,
	readdirSync,
	readFileSync,
	rmSync,
	symlinkSync,
} from "node:fs";
import {tmpdir} from "node:os";
import {dirname, join} from "node:path";
import {fileURLToPath} from "node:url";
import {afterAll, describe, expect, it} from "vite-plus/test";
import {z} from "zod";

const REPO_ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
// Per-copy state that must not be shared with the real checkout: the task cache lives in node_modules/.vite.
const UNSHARED_NODE_MODULES = new Set([".vite", ".vite-temp", ".cache", ".nitro"]);

const copies: string[] = [];

afterAll(() => {
	for (const copy of copies) rmSync(copy, {recursive: true, force: true});
});

function copyProject(): string {
	const copy = mkdtempSync(join(tmpdir(), "ccb-typecheck-cache-"));
	copies.push(copy);
	const files = [
		...execFileSync("git", ["ls-files", "-z", "--cached", "--others", "--exclude-standard"], {
			cwd: REPO_ROOT,
			encoding: "utf8",
		}).split("\0"),
		// Generated by the router plugin and gitignored, but tsc needs it.
		"src/routeTree.gen.ts",
	].filter((file) => file !== "" && existsSync(join(REPO_ROOT, file)));
	for (const file of files) cpSync(join(REPO_ROOT, file), join(copy, file));
	mkdirSync(join(copy, "node_modules"));
	for (const entry of readdirSync(join(REPO_ROOT, "node_modules"))) {
		if (!UNSHARED_NODE_MODULES.has(entry)) {
			symlinkSync(join(REPO_ROOT, "node_modules", entry), join(copy, "node_modules", entry));
		}
	}
	return copy;
}

function runTask(copy: string, task: string): {status: number | null; output: string} {
	const result = spawnSync(join(copy, "node_modules", ".bin", "vp"), ["run", "--cache", task], {
		cwd: copy,
		encoding: "utf8",
		env: {...process.env, PATH: `${join(copy, "node_modules", ".bin")}:${process.env["PATH"] ?? ""}`},
	});
	return {status: result.status, output: `${result.stdout}${result.stderr}`};
}

describe("typecheck task cache", () => {
	it("re-runs tsc after a source file changes instead of replaying a cached success", {timeout: 180_000}, () => {
		const copy = copyProject();

		expect(runTask(copy, "typecheck").status).toBe(0);

		appendFileSync(
			join(copy, "src", "lib", "agentation-endpoint.ts"),
			'\nexport const brokenType: number = "s";\n',
		);
		const second = runTask(copy, "typecheck");

		expect({status: second.status, reportsError: second.output.includes("TS2322")}).toStrictEqual({
			status: 1,
			reportsError: true,
		});
	});

	it("routes every package.json tsc run, including the build's, through the uncached typecheck task", () => {
		const {scripts} = z
			.object({scripts: z.record(z.string(), z.string())})
			.parse(JSON.parse(readFileSync(join(REPO_ROOT, "package.json"), "utf8")));

		expect({
			build: scripts["build"],
			scriptsCallingTsc: Object.keys(scripts).filter((name) => /\btsc\b/.test(scripts[name] ?? "")),
		}).toStrictEqual({build: "vp build && vp run typecheck", scriptsCallingTsc: []});
	});
});
