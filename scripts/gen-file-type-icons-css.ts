#!/usr/bin/env npx tsx
/**
 * Generate src/styles/file-type-icons.css: one custom property per palette
 * entry of each bundled file-type icon set (--fti-<name> for pierre,
 * --fti-<set>-<name> for catppuccin and vscode), light on :root and dark
 * under .dark, so FileTypeIcon's SSR output is theme-free.
 * Usage: npx tsx scripts/gen-file-type-icons-css.ts
 */

import {writeFileSync} from "node:fs";
import {join} from "node:path";
import {fileURLToPath} from "node:url";
import pierre from "../src/lib/file-type-icon-set.json";
import catppuccin from "../src/lib/file-type-icon-sets/catppuccin.json";
import vscode from "../src/lib/file-type-icon-sets/vscode.json";

const PALETTES: ReadonlyArray<readonly [prefix: string, palette: Record<string, readonly string[]>]> = [
	["--fti-", pierre.palette],
	["--fti-catppuccin-", catppuccin.palette],
	["--fti-vscode-", vscode.palette],
];

export function fileTypeIconsCss(): string
{
	const block = (selector: string, index: 0 | 1) =>
		`${selector}\n{\n${PALETTES.flatMap(([prefix, palette]) =>
			Object.entries(palette).map(([name, colors]) => `\t${prefix}${name}: ${colors[index]};\n`),
		).join("")}}\n`;
	return [
		"/* Generated by scripts/gen-file-type-icons-css.ts from src/lib/file-type-icon-set.json and src/lib/file-type-icon-sets/. Do not edit. */\n",
		block(":root", 0),
		block(".dark", 1),
	].join("\n");
}

if (process.argv[1] === fileURLToPath(import.meta.url))
{
	writeFileSync(join(import.meta.dirname, "../src/styles/file-type-icons.css"), fileTypeIconsCss());
}
