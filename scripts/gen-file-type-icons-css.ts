#!/usr/bin/env npx tsx
/**
 * Generate src/styles/file-type-icons.css: one --fti-<name> custom property per
 * palette entry of the bundled file-type icon set, light on :root and dark
 * under .dark, so FileTypeIcon's SSR output is theme-free.
 * Usage: npx tsx scripts/gen-file-type-icons-css.ts
 */

import {writeFileSync} from "node:fs";
import {join} from "node:path";
import {fileURLToPath} from "node:url";
import iconSet from "../src/lib/file-type-icon-set.json";

export function fileTypeIconsCss(): string {
	const entries = Object.entries(iconSet.palette);
	const block = (selector: string, index: 0 | 1) =>
		`${selector} {\n${entries.map(([name, colors]) => `\t--fti-${name}: ${colors[index]};\n`).join("")}}\n`;
	return [
		"/* Generated by scripts/gen-file-type-icons-css.ts from src/lib/file-type-icon-set.json. Do not edit. */\n",
		block(":root", 0),
		block(".dark", 1),
	].join("\n");
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
	writeFileSync(join(import.meta.dirname, "../src/styles/file-type-icons.css"), fileTypeIconsCss());
}
